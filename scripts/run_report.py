"""Run the Pillar 1 analysis on a trade journal.

Usage:
    uv run python scripts/run_report.py                       # testing journal -> README
    uv run python scripts/run_report.py journal.csv out_dir   # any journal -> out_dir/REPORT.md

With no arguments the public testing journal is analysed and the results are written into
README.md between the REPORT markers (figures stay in reports/testing_journal/figures/).
With arguments the report is written to out_dir/REPORT.md (use a git-ignored folder such as
reports/private/ for personal journals).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pandas as pd

from trade_analytics.report import build_report
from trade_analytics.schema import validate_trades

ROOT = Path(__file__).resolve().parents[1]
TESTING_JOURNAL = ROOT / "data/testing_journal/testing_journal.csv"
TESTING_OUT = ROOT / "reports/testing_journal"
README = ROOT / "README.md"
START, END = "<!-- REPORT:START -->", "<!-- REPORT:END -->"


def report_for_readme(report_md: str, figures_dir: str) -> str:
    """Adapt a generated report for embedding: drop its title, demote headings one level,
    point figure links at the figures folder."""
    lines = report_md.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    out = []
    for line in lines:
        if re.match(r"^#{2,5} ", line):
            line = "#" + line
        line = line.replace("](figures/", f"]({figures_dir}/")
        out.append(line)
    return "\n".join(out).strip()


def inject(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit(f"README is missing the {START} / {END} markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    note = "<!-- Generated by scripts/run_report.py. Do not edit by hand. -->"
    return f"{head}{START}\n{note}\n\n{block}\n\n{END}{tail}"


def main() -> None:
    to_readme = len(sys.argv) == 1
    journal = Path(sys.argv[1]) if len(sys.argv) > 1 else TESTING_JOURNAL
    out_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else TESTING_OUT
    trades = pd.read_csv(journal, parse_dates=["entry_time", "exit_time"])
    validate_trades(trades)
    summary = build_report(trades, out_dir, title="Testing journal: statistical assessment")
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2, default=float))

    report_path = out_dir / "REPORT.md"
    if to_readme:
        figures = (out_dir / "figures").relative_to(ROOT).as_posix()
        block = report_for_readme(report_path.read_text(), figures)
        README.write_text(inject(README.read_text(), block))
        report_path.unlink()
        print(f"results written into {README.name}; figures in {figures}/")
    else:
        print(f"report written to {report_path}")


if __name__ == "__main__":
    main()
